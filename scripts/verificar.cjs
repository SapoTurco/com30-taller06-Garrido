const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage();
  const errores = [];
  page.on('pageerror', e => errores.push(e.message));
  await page.goto('http://127.0.0.1:4200/');
  await page.locator('app-buscador').waitFor();
  const campo = page.locator('#busqueda');
  const filtro = page.locator('#filtro-estado');
  const pause = ms => page.waitForTimeout(ms);
  const ids = async () => (await page.locator('[data-testid=resultado] td:first-child').allTextContents()).map(Number);
  const llamadas = async () => Number(await page.getByTestId('llamadas').innerText());
  const historial = async () => page.locator('.search-history li').allTextContents();
  const esperado = JSON.parse(fs.readFileSync('docs/casos-esperados.json', 'utf8'));
  const obtenido = [];
  async function comprobar(caso, extra = {}) {
    const exp = esperado.find(c => c.caso === caso);
    const real = { caso, ids: await ids(), llamadas: await llamadas(), ...extra };
    assert.deepEqual(real.ids, exp.ids, caso + ': filas');
    assert.equal(real.llamadas, exp.llamadas, caso + ': llamadas');
    if (exp.mensaje) assert.ok((await page.locator('app-buscador').innerText()).includes(exp.mensaje), caso + ': mensaje');
    obtenido.push(real);
    console.log(JSON.stringify(real));
  }
  assert.equal(await llamadas(), 0);
  await campo.fill('motor');
  await pause(350);
  assert.match(await page.locator('#search-status').innerText(), /Buscando/);
  await pause(400); await comprobar('C1');
  await campo.fill('motor principal'); await pause(700); await comprobar('C2');
  await campo.fill('bomba'); await pause(700); await comprobar('C3');
  await campo.fill('bomba '); await pause(700); await comprobar('C4');
  await campo.fill('x'); await pause(700); await comprobar('C5');
  await campo.fill('zzz'); await pause(1100); await comprobar('C6');
  await campo.fill('motor'); await pause(700);
  const estados = {};
  for (const [estado, registros] of Object.entries(esperado[6].estados)) {
    await filtro.selectOption(estado); await pause(60);
    estados[estado] = await ids();
    assert.deepEqual(estados[estado], registros, 'C7 ' + estado);
    assert.equal(await llamadas(), 5);
    assert.equal(Number(await page.getByTestId('total').innerText()), registros.length);
  }
  await filtro.selectOption('Todos'); await comprobar('C7', { estados });
  await campo.fill(''); await campo.pressSequentially('válvula', { delay: 60 });
  await pause(700); await comprobar('C8');
  await campo.fill(''); await pause(350);
  await campo.fill('mo'); await pause(400);
  assert.equal(await llamadas(), 7, 'C9: la primera consulta debe haber salido');
  await campo.pressSequentially('tor', { delay: 40 });
  await pause(1500); await comprobar('C9', { historial: await historial() });
  assert.deepEqual(await historial(), esperado[8].historial);
  fs.mkdirSync('docs/evidencias', { recursive: true });
  await page.locator('app-buscador').screenshot({ path: 'docs/evidencias/C9.png' });
  const adicionales = [];
  for (const [texto, esperados] of [['VALVULA', [12]], ['ANDRES', [1,4,11]], ['EQ-012', [12]], ['Predictivo', [3,6,10]]]) {
    await campo.fill(texto); await pause(800);
    assert.deepEqual(await ids(), esperados, texto);
    adicionales.push({ texto, ids: await ids() });
  }
  assert.equal((await historial()).length, 5);
  // La edición y la eliminación originales deben reflejarse sin consultar otra vez.
  await campo.fill('motor'); await pause(700);
  await filtro.selectOption('Pendiente');
  const contadorAntes = await llamadas();
  await page.locator('#estado-1').selectOption('Finalizada'); await pause(80);
  assert.deepEqual(await ids(), [4,7]);
  await page.locator('.order-card').filter({ has: page.locator('#estado-4') }).getByRole('button', { name: 'Eliminar' }).click();
  await pause(80); assert.deepEqual(await ids(), [7]);
  assert.equal(await llamadas(), contadorAntes);
  adicionales.push({ caso: 'CRUD', resultado: 'cambio de estado y eliminación sin consultas nuevas' });
  await page.reload();
  await page.locator('#equipo').fill('EQ-099');
  await page.locator('#tipo').selectOption({ label: 'Preventivo' });
  await page.locator('#tecnico').fill('');
  assert.equal(await page.getByRole('button', { name: /Registrar orden/ }).isDisabled(), true);
  await page.locator('#tecnico').fill('Francisco Garrido');
  await page.locator('#fechaInicio').fill('2026-11-04');
  await page.locator('#fechaFin').fill('2026-11-10');
  await page.locator('#descripcion').fill('Inspección del motor de prueba');
  await page.locator('#tarea-0').fill('Revisión completa');
  await page.getByRole('button', { name: /Registrar orden/ }).click();
  await page.waitForFunction(() => document.querySelectorAll('.order-card').length === 13);
  assert.equal(await page.locator('.order-card').count(), 13);
  adicionales.push({ caso: 'Formulario T06', resultado: 'validación y registro de una orden, 13 tarjetas' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:4200/');
  await campo.fill('motor'); await pause(800);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sin desbordamiento móvil');
  await page.screenshot({ path: 'docs/evidencias/movil.png', fullPage: true });
  assert.deepEqual(errores, [], 'Sin errores de ejecución');
  fs.writeFileSync('docs/resultados-pruebas.json', JSON.stringify({ fecha: new Date().toISOString(), casos: obtenido, adicionales, errores }, null, 2));
  await context.close();
  await browser.close();
  console.log('OK: C1-C9, normalización, historial, CRUD, formulario y móvil.');
})().catch(e => { console.error(e); process.exit(1); });
